package cn.gdou.edu.timetable.data.remote

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class CasPasswordEncryptorTest {

    @Test
    fun encryptPassword_matchesStandardAesCbcRoundTrip() {
        val salt = "Ig44SE7ZZhlbx9fB"
        val prefix64 = "A".repeat(64)
        val iv16 = "1234567890abcdef"
        val rawPwd = "Gdou@2026#Test!"

        val encrypted = CasPasswordEncryptor.encryptPassword(
            plainPassword = rawPwd,
            pwdEncryptSalt = "  $salt  ",
            prefix64 = prefix64,
            iv16 = iv16
        )

        assertNotEquals(rawPwd, encrypted)
        // Exact Base64 ciphertext generated by live authserver.gdou.edu.cn/authserver/gdouThemeDz/static/common/encrypt.js
        assertEquals(
            "93Gb5cOmUMG/Zt6VP42t5od/3FZnPE+gaIinuKniKuBc3S8NgAMFISbKiKAoDSgMHoEsQ0rhRqdi2dE1ejh8xd4V+qF5S4s8mlztT0pfbKM=",
            encrypted
        )
        val decrypted = CasPasswordEncryptor.decryptForVerification(encrypted, salt, iv16)
        assertEquals(rawPwd, decrypted)
    }

    @Test
    fun encryptPassword_emptySaltReturnsPlaintext() {
        assertEquals("secret", CasPasswordEncryptor.encryptPassword("secret", ""))
    }

    @Test
    fun randomString_producesExpectedLengthAndAllowedCharset() {
        val allowed = "ABCDEFGHJKMNPQRSTWXYZabcdefhijkmnprstwxyz2345678".toSet()
        val s64 = CasPasswordEncryptor.randomString(64)
        val s16 = CasPasswordEncryptor.randomString(16)
        assertEquals(64, s64.length)
        assertEquals(16, s16.length)
        assertTrue(s64.all { it in allowed })
        assertTrue(s16.all { it in allowed })
    }

    @Test
    fun mfaChallengeDetection_matchesGdouReAuthAndMfaUrls() {
        val mfaUrls = listOf(
            "https://authserver.gdou.edu.cn/authserver/reAuthCheck/reAuthLoginView.do",
            "https://authserver.gdou.edu.cn/authserver/mfa/index.html",
            "https://authserver.gdou.edu.cn/authserver/multifactor/index.html"
        )
        mfaUrls.forEach { url ->
            val lower = url.lowercase()
            assertTrue(
                lower.contains("reauth") || lower.contains("/mfa") || lower.contains("multifactor")
            )
        }
    }

    @Test
    fun casFormSelection_picksPwdFormOverPrecedingDynamicLoginForm() {
        val mobileStyleHtml = """
            <div id="phoneLoginDiv" class="hide">
              <form id="loginFromId" class="loginFromClass" action="/authserver/login">
                <input type="hidden" name="cllt" value="dynamicLogin" />
                <input type="hidden" name="execution" value="e1s1" />
              </form>
            </div>
            <div id="pwdLoginDiv">
              <form id="loginFromId" class="loginFromClass" action="/authserver/login">
                <input type="hidden" name="cllt" value="userNameLogin" />
                <input type="hidden" id="pwdEncryptSalt" value="Ig44SE7ZZhlbx9fB" />
                <input type="hidden" name="execution" value="e2s1" />
              </form>
            </div>
        """.trimIndent()
        val doc = org.jsoup.Jsoup.parse(mobileStyleHtml)
        val pwdForm = doc.selectFirst("#pwdFromId") ?: doc.selectFirst("#pwdLoginDiv form")
        assertEquals("userNameLogin", pwdForm?.selectFirst("input[name=cllt]")?.attr("value"))
        assertEquals("Ig44SE7ZZhlbx9fB", pwdForm?.selectFirst("#pwdEncryptSalt")?.attr("value"))
        assertEquals("e2s1", pwdForm?.selectFirst("input[name=execution]")?.attr("value"))
    }
}
